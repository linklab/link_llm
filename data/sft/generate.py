_lines = []


def emit(u, b):
    _lines.append(f"{U} {u} {B} {b}")


INTERJ = ["", "", "", "", "아 ", "우와 ", "오 ", "그렇군요, ", "이야, "]   # 대부분은 없음


def deco(b):
    """봇 답에 감탄사 접두를 가끔 붙여 다양화."""
    p = rng.choice(INTERJ)
    return p + b if p else b


def emit_var(u, bot_pool, k=KVAR):
    """사용자 문장 u 에 봇 답 여러 개(중복 제거) 붙이기 = 1:다 매핑."""
    for b in rng.sample(bot_pool, min(k, len(bot_pool))):
        emit(u, deco(b))


