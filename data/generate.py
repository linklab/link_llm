def expand(slots, templates):
    out = []
    for x in slots:
        for ut, bots in templates:
            for bt in bots:
                out.append(line(ut.format(x=x), bt.format(x=x)))
    return out


def expand_pairs(pairs):
    out = []
    for u, bots in pairs:
        for b in bots:
            out.append(line(u, b))
    return out


def build_all():
    L = [line(u, b) for u, b in FIXED]
    L += expand(FOODS, LIKE) + expand(FOODS, FOOD_T)
    L += expand(ANIMALS, LIKE) + expand(ANIMALS, ANIMAL_T)
    L += expand(HOBBIES, LIKE) + expand(HOBBIES, HOBBY_T)
    L += expand(SUBJECTS, SUBJECT_T)
    L += expand(COLORS, COLOR_T)
    L += expand(CURIOUS, CURIOUS_T)
    L += expand(MUSIC, MUSIC_T) + expand(MUSIC, LIKE)
    L += expand(BOOKS, BOOK_T)
    L += expand(PLACES, PLACE_T)
    L += expand(JOBS, JOB_T)
    L += expand(TRANSPORT, TRANSPORT_T)
    L += expand(NATURE, NATURE_T)
    L += expand(CLOTHES, CLOTHES_T)
    L += expand(COUNTRIES, COUNTRY_T)
    L += expand(BODY, BODY_T)
    L += expand(SEASONS, SEASON_T)
    for grp in _EXTRA_GROUPS:
        L += expand(grp, GENERIC_T)
    L += expand_pairs(FEELINGS) + expand_pairs(WEATHER) + expand_pairs(DAILY)
    seen, uniq = set(), []
    for ln in L:
        if ln not in seen:
            seen.add(ln)
            uniq.append(ln)
    return uniq


def main():
    pool = build_all()
    rng = random.Random(SEED)
    rng.shuffle(pool)
    need = N_TRAIN + N_VALID
    if len(pool) < need:
        raise SystemExit(f"생성 풀 부족: {len(pool)} < {need}. 슬롯/템플릿을 더 늘리세요.")
    valid = sorted(pool[:N_VALID])
    train = sorted(pool[N_VALID:N_VALID + N_TRAIN])
    vocab = set(" ".join(train + valid).split())
    with open(os.path.join(HERE, "data.txt"), "w", encoding="utf-8") as f:
        f.write("\n".join(train) + "\n")
    with open(os.path.join(HERE, "valid.txt"), "w", encoding="utf-8") as f:
        f.write("\n".join(valid) + "\n")
    print(f"생성 완료: 풀 {len(pool)} → 학습 {len(train)} / 검증 {len(valid)} "
          f"(겹침 {len(set(train) & set(valid))}) · 어휘(토큰 종류) {len(vocab)}")


if __name__ == "__main__":
    main()
